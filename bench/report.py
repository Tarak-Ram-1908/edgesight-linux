#!/usr/bin/env python3
"""Collects every measurement into docs/results.md (+ charts in docs/img/).

Inputs (all optional - missing ones are reported as "n/a"):
  out/{prod,dev}/size-report.txt, out/prod/manifest.csv, out/prod/kernel.config
  bench/results/{boot-prod.jsonl,bench-edgesight.jsonl,bench-isolation.jsonl,elf-hardening.json}
  baseline/ubuntu/results/{ubuntu.json,boot.jsonl,bench-ubuntu.jsonl,python-stack-mib.txt}
"""
import csv
import json
import os
import statistics
import sys

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
P = lambda *a: os.path.join(ROOT, *a)


def kv(path):
    d = {}
    if os.path.exists(path):
        for line in open(path):
            if "=" in line:
                for tok in line.split():
                    if "=" in tok:
                        k, v = tok.split("=", 1)
                        d[k] = v
    return d


def jl(path):
    if not os.path.exists(path):
        return []
    return [json.loads(x) for x in open(path) if x.strip().startswith("{")]


def js(path):
    return json.load(open(path)) if os.path.exists(path) else {}


MB = 1024 * 1024
prod, dev = kv(P("out/prod/size-report.txt")), kv(P("out/dev/size-report.txt"))
ub = js(P("baseline/ubuntu/results/ubuntu.json"))
boot_es = jl(P("bench/results/boot-prod.jsonl"))
boot_ub = jl(P("baseline/ubuntu/results/boot.jsonl"))
bench_es = jl(P("bench/results/bench-edgesight.jsonl"))
bench_ub = jl(P("baseline/ubuntu/results/bench-ubuntu.jsonl"))
iso = jl(P("bench/results/bench-isolation.jsonl"))
elf = js(P("bench/results/elf-hardening.json"))
ab = jl(P("bench/results/ab-compare.jsonl"))


def khc(name):
    p = P(f"bench/results/khc-{name}-full.txt")
    if not os.path.exists(p):
        return None
    last = open(p).read().strip().splitlines()[-1]
    import re
    m = re.search(r"'OK' - (\d+) / 'FAIL' - (\d+)", last)
    return (int(m.group(1)), int(m.group(2))) if m else None


khc_es, khc_ub = khc("edgesight"), khc("ubuntu")

pkgs_es = None
if os.path.exists(P("out/prod/manifest.csv")):
    with open(P("out/prod/manifest.csv")) as f:
        pkgs_es = sum(1 for _ in csv.DictReader(f))
kcfg_y = None
if os.path.exists(P("out/prod/kernel.config")):
    kcfg_y = sum(1 for l in open(P("out/prod/kernel.config")) if l.rstrip().endswith("=y"))
py_stack = open(P("baseline/ubuntu/results/python-stack-mib.txt")).read().strip() if os.path.exists(
    P("baseline/ubuntu/results/python-stack-mib.txt")) else None


def mean(xs):
    xs = [x for x in xs if isinstance(x, (int, float))]
    return statistics.fmean(xs) if xs else None


def sd(xs):
    xs = [x for x in xs if isinstance(x, (int, float))]
    return statistics.pstdev(xs) if len(xs) > 1 else 0.0


def f(x, fmt="{:.1f}"):
    return "n/a" if x is None else fmt.format(x)


def red(a, b):
    if a is None or b is None or b == 0:
        return "n/a"
    return f"{100 * (1 - a / b):.1f} %"


rootfs_es = int(prod["rootfs_squashfs_bytes"]) if "rootfs_squashfs_bytes" in prod else None
kernel_es = int(prod["bzImage_bytes"]) if "bzImage_bytes" in prod else None
img_es_z = int(prod["disk_img_zstd_bytes"]) if "disk_img_zstd_bytes" in prod else None
rootfs_ub = ub.get("rootfs_used_bytes")
kernel_ub = (ub.get("kernel_bytes") or 0) + (ub.get("initrd_bytes") or 0) + (ub.get("modules_bytes") or 0) or None
mem_es = mean([b.get("sys_mem_used_mib") for b in boot_es])
mem_ub = ub.get("sys_mem_used_mib")
boot_es_wall = mean([b.get("launch_to_ready_s") for b in boot_es])
boot_es_k = mean([b.get("kernel_to_ready_s") for b in boot_es])
boot_ub_wall = mean([b.get("launch_to_app_ready_s") for b in boot_ub])
boot_ub_k = mean([b.get("kernel_to_app_ready_s") for b in boot_ub])
# Prefer the interleaved boot comparison (same host conditions for both systems)
ab_boot = jl(P("bench/results/ab-boot.jsonl"))
if ab_boot:
    def _m(sysn, key):
        xs = sorted(b[key] for b in ab_boot if b["system"] == sysn and isinstance(b.get(key), (int, float)))
        return xs[len(xs) // 2] if xs else None
    boot_es_wall, boot_es_k, mem_es = _m("edgesight", "launch_to_ready_s"), _m("edgesight", "kernel_to_ready_s"), _m("edgesight", "sys_mem_used_mib")
    boot_ub_wall, boot_ub_k, mem_ub = _m("ubuntu", "launch_to_ready_s"), _m("ubuntu", "kernel_to_ready_s"), _m("ubuntu", "sys_mem_used_mib")
    boot_es = [b for b in ab_boot if b["system"] == "edgesight"]

out = []
w = out.append
w("# EdgeSight - measured results\n")
w("_Generated by `bench/report.py` from the raw files in `bench/results/`, `baseline/ubuntu/results/` and `out/`._\n")
w("## System footprint: EdgeSight prod vs Ubuntu Server 24.04 (same QEMU machine)\n")
w("| Metric | EdgeSight | Ubuntu 24.04 | Reduction |")
w("|---|---:|---:|---:|")
w(f"| Root filesystem (bytes on disk) | {f(rootfs_es and rootfs_es / MB)} MiB | {f(rootfs_ub and rootfs_ub / MB)} MiB | {red(rootfs_es, rootfs_ub)} |")
w(f"| Kernel (+initrd +modules) | {f(kernel_es and kernel_es / MB, '{:.2f}')} MiB | {f(kernel_ub and kernel_ub / MB)} MiB | {red(kernel_es, kernel_ub)} |")
w(f"| Loadable kernel modules | 0 | {ub.get('modules', 'n/a')} | |")
w(f"| Packages | {pkgs_es or 'n/a'} | {ub.get('packages', 'n/a')} | {red(pkgs_es, ub.get('packages'))} |")
w(f"| RAM used after boot, service running | {f(mem_es)} MiB | {f(mem_ub)} MiB | {red(mem_es, mem_ub)} |")
w(f"| Power-on → application ready | {f(boot_es_wall, '{:.2f}')} s | {f(boot_ub_wall, '{:.2f}')} s | {red(boot_es_wall, boot_ub_wall)} |")
w(f"| Kernel start → application ready | {f(boot_es_k, '{:.2f}')} s | {f(boot_ub_k, '{:.2f}')} s | {red(boot_es_k, boot_ub_k)} |")
w(f"| Running processes | (hidepid; see dev) | {ub.get('processes', 'n/a')} | |")
w(f"| Listening sockets | 3 (8080, 1883, 5000) | {ub.get('listening_sockets', 'n/a')} | |")
w(f"| setuid/setgid files | 0 | {ub.get('setuid_setgid_files', 'n/a')} | |")
ub_img = int(open(P("baseline/ubuntu/results/image-bytes.txt")).read()) if os.path.exists(P("baseline/ubuntu/results/image-bytes.txt")) else None
w(f"| Distributable image (EdgeSight: whole A/B disk, zstd · Ubuntu: official compressed qcow2) | {f(img_es_z and img_es_z / MB)} MiB | {f(ub_img and ub_img / MB)} MiB | {red(img_es_z, ub_img)} |")
w(f"| Signed OTA bundle | {f(int(prod['bundle_bytes']) / MB if 'bundle_bytes' in prod else None)} MiB | | |")
if py_stack:
    w(f"| Python ML stack the stock deployment needs (venv: onnxruntime+numpy+pillow) | not needed | {py_stack} MiB | |")
w("")
if dev:
    w(f"Dev variant (shell, SSH, strace, htop, Python 3): root fs {int(dev['rootfs_squashfs_bytes']) / MB:.1f} MiB "
      f"(+{(int(dev['rootfs_squashfs_bytes']) - (rootfs_es or 0)) / MB:.1f} MiB vs prod).\n")
if kcfg_y:
    w(f"Kernel: {kcfg_y} options built in (`=y`), 0 modules.\n")
if ab_boot:
    w(f"Boot and RAM rows: medians of {len(boot_es)} interleaved boots per system (EdgeSight, Ubuntu, EdgeSight, …; "
      f"`bench/ab-boot.sh`). EdgeSight power-on→ready range "
      f"{min(b['launch_to_ready_s'] for b in boot_es):.2f}–{max(b['launch_to_ready_s'] for b in boot_es):.2f} s.\n")
elif len(boot_es) > 1:
    w(f"Boot statistics, EdgeSight ({len(boot_es)} runs): power-on→ready {boot_es_wall:.2f} ± {sd([b['launch_to_ready_s'] for b in boot_es]):.2f} s, "
      f"kernel→ready {boot_es_k:.2f} ± {sd([b['kernel_to_ready_s'] for b in boot_es]):.2f} s.\n")

if khc_es and khc_ub:
    w(f"Kernel-hardening-checker (same rule set): EdgeSight **{khc_es[0]} OK / {khc_es[1]} FAIL**, "
      f"Ubuntu 24.04 generic {khc_ub[0]} OK / {khc_ub[1]} FAIL.\n")

if ab:
    def med(xs):
        xs = sorted(x for x in xs if x is not None)
        return xs[len(xs) // 2] if xs else None
    rounds = max(r["round"] for r in ab)
    w(f"## Inference, interleaved A/B on the same host ({rounds} rounds, median)\n")
    w("Both VMs booted side by side and idle; each configuration runs on EdgeSight, then Ubuntu (same "
      "`edgesightd` binary + libraries), then Ubuntu's stock Python/pip pipeline, round after round.\n")
    w("| Model / threads | System | infer p50 ms | infer p99 ms | end-to-end FPS | CPU ms/frame | peak RSS MiB |")
    w("|---|---|---:|---:|---:|---:|---:|")
    order = {"edgesight": 0, "ubuntu": 1, "ubuntu-python": 2}
    names = {"edgesight": "EdgeSight (edgesightd)", "ubuntu": "Ubuntu (same edgesightd)", "ubuntu-python": "Ubuntu (Python + pip ORT)"}
    for label in sorted({r["label"] for r in ab}):
        for sysn in sorted({r["system"] for r in ab if r["label"] == label}, key=lambda s: order.get(s, 9)):
            g = [r for r in ab if r["label"] == label and r["system"] == sysn]
            w(f"| {label} | {names.get(sysn, sysn)} | {med([r['latency_ms']['infer']['p50'] for r in g]):.1f} | "
              f"{med([r['latency_ms']['infer']['p99'] for r in g]):.1f} | {med([r['fps'] for r in g]):.1f} | "
              f"{med([r['cpu_ms_per_frame'] for r in g]):.1f} | {med([r['peak_rss_mib'] for r in g]):.0f} |")
    w("")

w("## Inference matrix on EdgeSight (SSD-MobileNet-v1 COCO, 300×300, frames 640×480, 2 vCPU)\n")
def _med(xs):
    xs = sorted(xs)
    return xs[len(xs) // 2]


# collapse repeated rounds -> one row per configuration with medians
_order, _groups = [], {}
for r in bench_es:
    l = r.get("label", r.get("engine"))
    if l not in _groups:
        _order.append(l)
        _groups[l] = []
    _groups[l].append(r)
bench_med = []
for l in _order:
    g = _groups[l]
    bench_med.append({"label": l, "n": len(g), "fps": _med([x["fps"] for x in g]),
                      "cpu_ms_per_frame": _med([x["cpu_ms_per_frame"] for x in g]),
                      "peak_rss_mib": _med([x["peak_rss_mib"] for x in g]),
                      "dets_per_frame": _med([x["dets_per_frame"] for x in g]),
                      "latency_ms": {"infer": {"p50": _med([x["latency_ms"]["infer"]["p50"] for x in g]),
                                               "p99": _med([x["latency_ms"]["infer"]["p99"] for x in g])},
                                     "total": {"p50": _med([x["latency_ms"]["total"]["p50"] for x in g])}}})
rounds_n = max((b["n"] for b in bench_med), default=0)
w(f"Median of {rounds_n} interleaved rounds per configuration.\n")
w("| Configuration | FPS | infer p50 ms | infer p99 ms | end-to-end p50 ms | CPU ms/frame | peak RSS MiB | dets/frame |")
w("|---|---:|---:|---:|---:|---:|---:|---:|")
for r in bench_med:
    L = r["latency_ms"]
    w(f"| {r['label']} | {r['fps']:.1f} | {L['infer']['p50']:.1f} | {L['infer']['p99']:.1f} | {L['total']['p50']:.1f} | "
      f"{r['cpu_ms_per_frame']:.1f} | {r['peak_rss_mib']:.0f} | {r['dets_per_frame']:.2f} |")
w("")
if iso:
    w("## CPU isolation ablation (ORT INT8, 1 thread, 3 busy-loop hogs)\n")
    w("| Setup | infer p50 ms | infer p99 ms | p99/p50 | stdev ms |")
    w("|---|---:|---:|---:|---:|")
    for r in iso:
        L = r["latency_ms"]["infer"]
        w(f"| {r['label']} | {L['p50']:.2f} | {L['p99']:.2f} | {L['p99'] / L['p50']:.2f} | {L['stdev']:.2f} |")
    w("")
if elf:
    w("## Userland hardening (all ELF objects in the prod root fs)\n")
    w(f"{elf['elf_total']} objects: PIE/DSO {elf['pie']}, full RELRO {elf['full_relro']}, NX {elf['nx']}, "
      f"stack canary {elf['canary']}, FORTIFY {elf['fortify']}.\n")

open(P("docs/results.md"), "w").write("\n".join(out) + "\n")
print("\n".join(out))

# ---------------------------------------------------------------- charts
try:
    import matplotlib
    matplotlib.use("Agg")
    import matplotlib.pyplot as plt
except ImportError:
    print("matplotlib not available - charts skipped", file=sys.stderr)
    sys.exit(0)

os.makedirs(P("docs/img"), exist_ok=True)
INK, MUTED, GRID = "#1f2328", "#59636e", "#d1d9e0"
ES, UB = "#2f81f7", "#8c959f"
plt.rcParams.update({"font.size": 10, "axes.edgecolor": GRID, "axes.labelcolor": INK, "xtick.color": MUTED,
                     "ytick.color": MUTED, "axes.spines.top": False, "axes.spines.right": False})

pairs = [("Root fs (MiB)", rootfs_es and rootfs_es / MB, rootfs_ub and rootfs_ub / MB),
         ("RAM used (MiB)", mem_es, mem_ub),
         ("Boot to app (s)", boot_es_wall, boot_ub_wall),
         ("Packages", pkgs_es, ub.get("packages"))]
pairs = [p for p in pairs if p[1] is not None and p[2] is not None]
if pairs:
    fig, axes = plt.subplots(1, len(pairs), figsize=(2.6 * len(pairs), 3.0))
    axes = axes if len(pairs) > 1 else [axes]
    for ax, (title, a, b) in zip(axes, pairs):
        bars = ax.bar(["EdgeSight", "Ubuntu"], [a, b], color=[ES, UB], width=0.6)
        ax.set_title(title, color=INK, fontsize=10)
        ax.yaxis.grid(True, color=GRID, linewidth=0.6)
        ax.set_axisbelow(True)
        for bar, v in zip(bars, [a, b]):
            txt = f"{v:,.0f}" if (v >= 100 or float(v).is_integer()) else f"{v:,.1f}"
            ax.annotate(txt, (bar.get_x() + bar.get_width() / 2, v),
                        ha="center", va="bottom", fontsize=9, color=INK, xytext=(0, 2), textcoords="offset points")
        ax.text(0.5, 0.92, f"−{100 * (1 - a / b):.0f}%", transform=ax.transAxes, ha="center", color=ES, fontweight="bold")
    fig.tight_layout()
    fig.savefig(P("docs/img/footprint.png"), dpi=160)

if ab:
    labels = sorted({r["label"] for r in ab})
    systems = [("edgesight", "EdgeSight", ES), ("ubuntu", "Ubuntu, same binary", UB), ("ubuntu-python", "Ubuntu, Python/pip", "#d4a72c")]
    fig, ax = plt.subplots(figsize=(7.5, 3.0))
    width = 0.26
    for k, (sk, sname, col) in enumerate(systems):
        vals = []
        for l in labels:
            g = sorted(r["latency_ms"]["infer"]["p50"] for r in ab if r["label"] == l and r["system"] == sk)
            vals.append(g[len(g) // 2] if g else 0)
        ax.bar([i + (k - 1) * width for i in range(len(labels))], vals, width=width, color=col, label=sname)
    ax.set_xticks(range(len(labels)), labels)
    ax.set_ylabel("inference p50, ms (median of rounds)")
    ax.legend(frameon=False, fontsize=8)
    ax.yaxis.grid(True, color=GRID, linewidth=0.6)
    ax.set_axisbelow(True)
    fig.tight_layout()
    fig.savefig(P("docs/img/ab-inference.png"), dpi=160)

rows = bench_med
if rows:
    rows = sorted(rows, key=lambda r: r["latency_ms"]["infer"]["p50"])
    fig, ax = plt.subplots(figsize=(8, 0.34 * len(rows) + 1))
    labels = [r["label"] for r in rows]
    p50 = [r["latency_ms"]["infer"]["p50"] for r in rows]
    p99 = [r["latency_ms"]["infer"]["p99"] for r in rows]
    col = [UB if l.startswith("ubuntu") else ES for l in labels]
    y = range(len(rows))
    ax.barh(y, p50, color=col, height=0.6)
    ax.scatter(p99, y, color=INK, s=12, zorder=3, label="p99")
    ax.set_yticks(list(y), labels, fontsize=8)
    ax.invert_yaxis()
    ax.set_xlabel("inference latency per frame, ms (bar = p50, dot = p99)")
    ax.xaxis.grid(True, color=GRID, linewidth=0.6)
    ax.set_axisbelow(True)
    fig.tight_layout()
    fig.savefig(P("docs/img/inference.png"), dpi=160)

if iso:
    fig, ax = plt.subplots(figsize=(5.5, 2.6))
    labels = [r["label"] for r in iso]
    p50 = [r["latency_ms"]["infer"]["p50"] for r in iso]
    p99 = [r["latency_ms"]["infer"]["p99"] for r in iso]
    x = range(len(iso))
    ax.bar([i - 0.18 for i in x], p50, width=0.36, color=ES, label="p50")
    ax.bar([i + 0.18 for i in x], p99, width=0.36, color="#9ec5fe", label="p99")
    ax.set_xticks(list(x), labels, fontsize=8)
    ax.set_ylabel("ms")
    ax.legend(frameon=False, fontsize=8)
    ax.yaxis.grid(True, color=GRID, linewidth=0.6)
    ax.set_axisbelow(True)
    fig.tight_layout()
    fig.savefig(P("docs/img/isolation.png"), dpi=160)
print("charts written to docs/img/", file=sys.stderr)
