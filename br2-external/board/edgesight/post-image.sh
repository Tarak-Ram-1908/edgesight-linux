#!/bin/bash
# EdgeSight post-image: turns rootfs.squashfs + bzImage + GRUB into
#   disk.img          bootable GPT image (A/B slots, verity-protected roots)
#   edgesight-<v>.raucb   signed OTA update bundle for the same build
#   size-report.txt   numbers used in the report
set -euo pipefail

BOARD_DIR="$(cd "$(dirname "$0")" && pwd)"
REPO_DIR="$(cd "$BOARD_DIR/../../.." && pwd)"
VARIANT="${2:-prod}"
VERSION="${EDGESIGHT_VERSION:-1.0.0}"
B="$BINARIES_DIR"

VERITYSETUP="$(command -v veritysetup || true)"
[ -x "$HOST_DIR/sbin/veritysetup" ] && VERITYSETUP="$HOST_DIR/sbin/veritysetup"
[ -x "$HOST_DIR/bin/veritysetup" ] && VERITYSETUP="$HOST_DIR/bin/veritysetup"
[ -n "$VERITYSETUP" ] || { echo "veritysetup not found" >&2; exit 1; }

# ---------------------------------------------------------------- dm-verity
# squashfs is already padded to 4 KiB; the Merkle tree is appended in the same
# partition (no superblock), so the kernel needs only cmdline parameters.
cp "$B/rootfs.squashfs" "$B/rootfs.verity"
DATA_BYTES=$(stat -c %s "$B/rootfs.squashfs")
if [ $((DATA_BYTES % 4096)) -ne 0 ]; then
    truncate -s $(( (DATA_BYTES + 4095) / 4096 * 4096 )) "$B/rootfs.verity"
    DATA_BYTES=$(stat -c %s "$B/rootfs.verity")
fi
DATA_BLOCKS=$((DATA_BYTES / 4096))
# Deterministic salt (reproducible builds): derived from the filesystem content
SALT=$(sha256sum "$B/rootfs.squashfs" | cut -c1-64)
"$VERITYSETUP" format --no-superblock --hash-offset="$DATA_BYTES" \
    --data-blocks="$DATA_BLOCKS" --salt="$SALT" \
    "$B/rootfs.verity" "$B/rootfs.verity" > "$B/verity.txt"
ROOT_HASH=$(sed -n 's/^Root hash:[[:space:]]*//p' "$B/verity.txt")
[ -n "$ROOT_HASH" ] || { cat "$B/verity.txt"; echo "no root hash" >&2; exit 1; }

cat > "$B/verity.cfg" <<EOF
# generated by post-image.sh - dm-verity geometry of the paired rootfs slot
set verity_sectors=$((DATA_BYTES / 512))
set verity_blocks=$DATA_BLOCKS
set verity_hash_start=$DATA_BLOCKS
set verity_root=$ROOT_HASH
set verity_salt=$SALT
EOF

# ---------------------------------------------------------------- GRUB
mkdir -p "$B/efi-part/EFI/BOOT"
cp "$BOARD_DIR/grub.cfg" "$B/efi-part/EFI/BOOT/grub.cfg"
# grubenv must be exactly 1024 bytes; both slots start identical and good
{
    printf '# GRUB Environment Block\n'
    printf 'ORDER=A B\nA_OK=1\nA_TRY=0\nB_OK=1\nB_TRY=0\n'
} > "$B/grubenv.head"
HEAD_LEN=$(stat -c %s "$B/grubenv.head")
{ cat "$B/grubenv.head"; head -c $((1024 - HEAD_LEN)) /dev/zero | tr '\0' '#'; } \
    > "$B/efi-part/EFI/BOOT/grubenv"
rm -f "$B/grubenv.head"

# ---------------------------------------------------------------- /data
rm -f "$B/data.ext4"
E2FS_DIR="$HOST_DIR/sbin"; [ -x "$E2FS_DIR/mkfs.ext4" ] || E2FS_DIR="$HOST_DIR/bin"
E2FSPROGS_FAKE_TIME="${SOURCE_DATE_EPOCH:-1767225600}" "$E2FS_DIR/mkfs.ext4" -q -L data -U clear \
    -E root_owner=0:0,hash_seed=e5e5e5e5-0000-4000-8000-0000000000aa "$B/data.ext4" 160M   # all-zero seed = "random"

# ---------------------------------------------------------------- disk image
# clamp mtimes of everything copied into FAT images (mcopy -p preserves them)
STAMP="@${SOURCE_DATE_EPOCH:-1767225600}"
find "$B/efi-part" -exec touch -h -d "$STAMP" {} +
touch -d "$STAMP" "$B/bzImage" "$B/verity.cfg"
support/scripts/genimage.sh -c "$BOARD_DIR/genimage.cfg"

# ---------------------------------------------------------------- RAUC bundle
KEYS="$REPO_DIR/keys"
if [ -f "$KEYS/dev.key.pem" ] && [ -f "$KEYS/dev.cert.pem" ]; then
    BDIR="$B/bundle"
    rm -rf "$BDIR" && mkdir -p "$BDIR"
    cp "$B/rootfs.verity" "$BDIR/rootfs.img"
    cp "$B/boot.vfat" "$BDIR/boot.vfat"
    cat > "$BDIR/manifest.raucm" <<EOF
[update]
compatible=edgesight-x86_64
version=$VERSION
description=EdgeSight Linux $VERSION ($VARIANT)

[bundle]
format=verity

[image.rootfs]
filename=rootfs.img

[image.boot]
filename=boot.vfat
EOF
    rm -f "$B/edgesight-$VERSION.raucb"
    "$HOST_DIR/bin/rauc" bundle --cert="$KEYS/dev.cert.pem" --key="$KEYS/dev.key.pem" \
        "$BDIR" "$B/edgesight-$VERSION.raucb"
    rm -rf "$BDIR"
else
    echo "post-image: no signing keys - skipping RAUC bundle" >&2
fi

# ---------------------------------------------------------------- report
{
    echo "variant=$VARIANT version=$VERSION"
    echo "bzImage_bytes=$(stat -c %s "$B/bzImage")"
    echo "rootfs_squashfs_bytes=$(stat -c %s "$B/rootfs.squashfs")"
    echo "rootfs_verity_bytes=$(stat -c %s "$B/rootfs.verity")"
    echo "disk_img_bytes=$(stat -c %s "$B/disk.img")"
    echo "disk_img_allocated_bytes=$(( $(stat -c %b "$B/disk.img") * 512 ))"
    echo "disk_img_zstd_bytes=$(zstd -19 -T0 -q -c "$B/disk.img" | wc -c)"
    [ -f "$B/edgesight-$VERSION.raucb" ] && echo "bundle_bytes=$(stat -c %s "$B/edgesight-$VERSION.raucb")"
    echo "root_hash=$ROOT_HASH"
} > "$B/size-report.txt"
cat "$B/size-report.txt"
